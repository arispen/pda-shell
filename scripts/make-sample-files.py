#!/usr/bin/env python3
"""Generate the realistic sample documents in assets/sample-files.

The development session copies these into its isolated HOME (~/Documents) so
the real applications have real work to open: a populated .xlsx with
formulas and formatting, a formatted Markdown document, a multi-page PDF, a
small local web site, and deeply nested folders with long file names.

Standard library only, deterministic output (fixed timestamps), so the
generated files can be committed and re-generated byte for byte:

    ./scripts/make-sample-files.py            # writes assets/sample-files
    ./scripts/make-sample-files.py OUT_DIR
"""
import os
import sys
import zipfile
from xml.sax.saxutils import escape

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "assets", "sample-files")
STAMP = (2026, 10, 1, 9, 30, 0)


def write(rel, data):
    path = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    mode = "wb" if isinstance(data, bytes) else "w"
    with open(path, mode, **({} if mode == "wb" else {"encoding": "utf-8", "newline": "\n"})) as f:
        f.write(data)


# --- spreadsheet ---------------------------------------------------------------

def col(i):
    return "ABCDEFGHIJKLMNOPQRSTUVWXYZ"[i]


def xlsx(path, sheets):
    """sheets: [(name, rows, col_widths)]; a row is a list of cells, a cell
    is None, a number, a str, ("f", formula, cached) or (style, value)."""
    strings, index = [], {}

    def sst(s):
        if s not in index:
            index[s] = len(strings)
            strings.append(s)
        return index[s]

    def cell_xml(ref, cell):
        style = 0
        if isinstance(cell, tuple) and cell[0] in ("h", "n", "t"):
            style = {"h": 1, "n": 2, "t": 3}[cell[0]]
            cell = cell[1]
        s = f' s="{style}"' if style else ""
        if isinstance(cell, tuple) and cell[0] == "f":
            return f'<c r="{ref}"{s}><f>{escape(cell[1])}</f><v>{cell[2]}</v></c>'
        if isinstance(cell, str):
            return f'<c r="{ref}"{s} t="s"><v>{sst(cell)}</v></c>'
        return f'<c r="{ref}"{s}><v>{cell}</v></c>'

    sheet_xml = []
    for _, rows, widths in sheets:
        cols = "".join(
            f'<col min="{i + 1}" max="{i + 1}" width="{w}" customWidth="1"/>' for i, w in enumerate(widths)
        )
        body = []
        for r, row in enumerate(rows, 1):
            cells = "".join(cell_xml(f"{col(c)}{r}", v) for c, v in enumerate(row) if v is not None)
            body.append(f'<row r="{r}">{cells}</row>')
        sheet_xml.append(
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
            '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>'
            f"<cols>{cols}</cols><sheetData>{''.join(body)}</sheetData></worksheet>"
        )

    ns = 'xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"'
    rel_ns = 'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"'
    files = {
        "[Content_Types].xml": (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Default Extension="xml" ContentType="application/xml"/>'
            '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
            + "".join(
                f'<Override PartName="/xl/worksheets/sheet{i + 1}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
                for i in range(len(sheets))
            )
            + '<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>'
            '<Override PartName="/xl/sharedStrings.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sharedStrings+xml"/>'
            "</Types>"
        ),
        "_rels/.rels": (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>'
            "</Relationships>"
        ),
        "xl/workbook.xml": (
            f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?><workbook {ns} {rel_ns}><sheets>'
            + "".join(
                f'<sheet name="{escape(name)}" sheetId="{i + 1}" r:id="rId{i + 1}"/>' for i, (name, _, _) in enumerate(sheets)
            )
            + "</sheets></workbook>"
        ),
        "xl/_rels/workbook.xml.rels": (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            + "".join(
                f'<Relationship Id="rId{i + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet{i + 1}.xml"/>'
                for i in range(len(sheets))
            )
            + f'<Relationship Id="rId{len(sheets) + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>'
            f'<Relationship Id="rId{len(sheets) + 2}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/sharedStrings" Target="sharedStrings.xml"/>'
            "</Relationships>"
        ),
        # Styles: 0 default, 1 header (bold, filled), 2 money, 3 total (bold money).
        "xl/styles.xml": (
            f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?><styleSheet {ns}>'
            '<numFmts count="1"><numFmt numFmtId="164" formatCode="#,##0.00"/></numFmts>'
            '<fonts count="2"><font><sz val="10"/><name val="DejaVu Sans"/></font>'
            '<font><b/><sz val="10"/><name val="DejaVu Sans"/></font></fonts>'
            '<fills count="3"><fill><patternFill patternType="none"/></fill><fill><patternFill patternType="gray125"/></fill>'
            '<fill><patternFill patternType="solid"><fgColor rgb="FFDCE6F2"/></patternFill></fill></fills>'
            '<borders count="2"><border/><border><top style="thin"/></border></borders>'
            '<cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs>'
            '<cellXfs count="4"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/>'
            '<xf numFmtId="0" fontId="1" fillId="2" borderId="0" applyFont="1" applyFill="1"/>'
            '<xf numFmtId="164" fontId="0" fillId="0" borderId="0" applyNumberFormat="1"/>'
            '<xf numFmtId="164" fontId="1" fillId="0" borderId="1" applyNumberFormat="1" applyFont="1" applyBorder="1"/></cellXfs>'
            "</styleSheet>"
        ),
    }
    for i, xml in enumerate(sheet_xml):
        files[f"xl/worksheets/sheet{i + 1}.xml"] = xml
    files["xl/sharedStrings.xml"] = (
        f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?><sst {ns} count="{len(strings)}" uniqueCount="{len(strings)}">'
        + "".join(f"<si><t>{escape(s)}</t></si>" for s in strings)
        + "</sst>"
    )

    full = os.path.join(OUT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    order = ["[Content_Types].xml", "_rels/.rels", "xl/workbook.xml", "xl/_rels/workbook.xml.rels", "xl/styles.xml"]
    order += sorted(k for k in files if k not in order)
    with zipfile.ZipFile(full, "w", zipfile.ZIP_DEFLATED) as z:
        for name in order:
            info = zipfile.ZipInfo(name, STAMP)
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, files[name])


def budget():
    months = ["January", "February", "March", "April", "May", "June", "July",
              "August", "September", "October", "November", "December"]
    header = [("h", h) for h in ["Month", "Income", "Rent", "Food", "Transport", "Other", "Savings"]]
    rows = [header]
    totals = [0.0] * 6
    for i, m in enumerate(months):
        income = 4200 + (i % 3) * 150
        values = [income, 1450, 520 + (i * 37) % 140, 96 + (i * 11) % 40, 180 + (i * 53) % 210]
        r = i + 2
        saving = values[0] - sum(values[1:])
        rows.append([m] + [("n", v) for v in values] + [("n", ("f", f"B{r}-SUM(C{r}:F{r})", saving))])
        for k, v in enumerate(values + [saving]):
            totals[k] += v
    last = len(months) + 1
    rows.append([("h", "Total")] + [("t", ("f", f"SUM({col(c)}2:{col(c)}{last})", totals[c - 1])) for c in range(1, 7)])
    rows.append([])
    rows.append(["Average saving", ("n", ("f", f"AVERAGE(G2:G{last})", round(totals[5] / 12, 6)))])
    notes = [
        [("h", "Notes")],
        ["Figures are monthly, in CHF."],
        ["Savings = income minus all expenses (column G is a formula)."],
        ["Edit a number in the Budget sheet and the totals update."],
    ]
    xlsx("Budget 2026.xlsx", [("Budget", rows, [15, 12, 12, 11, 11, 11, 12]), ("Notes", notes, [60])])


