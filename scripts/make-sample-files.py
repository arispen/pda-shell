def pdf(path, title, pages):
    """pages: list of [(kind, text)], kind in h1/h2/p. Letter-free A5 pages,
    Helvetica, naive word wrapping."""
    width, height, margin = 420, 595, 42
    sizes = {"h1": 18, "h2": 13, "p": 10.5}
    fonts = {"h1": "F2", "h2": "F2", "p": "F1"}

    def wrap(text, size):
        max_chars = int((width - 2 * margin) / (size * 0.5))
        lines, line = [], ""
        for word in text.split():
            if len(line) + len(word) + 1 > max_chars:
                lines.append(line)
                line = word
            else:
                line = f"{line} {word}".strip()
        return lines + [line]

    def esc(s):
        return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")

    objects = []  # index i -> object number i+1

    def add(body):
        objects.append(body)
        return len(objects)

    catalog = add(None)
    pages_obj = add(None)
    f1 = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>")
    f2 = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>")
    kids = []
    for n, blocks in enumerate(pages, 1):
        y = height - margin
        ops = []
        for kind, text in blocks:
            size = sizes[kind]
            y -= size * (0.6 if kind == "p" else 1.2)
            for line in wrap(text, size):
                y -= size * 1.35
                ops.append(f"BT /{fonts[kind]} {size} Tf {margin} {y:.1f} Td ({esc(line)}) Tj ET")
            y -= size * 0.4
        ops.append(f"BT /F1 8 Tf {margin} 24 Td ({esc(title)}) Tj ET")
        ops.append(f"BT /F1 8 Tf {width - margin - 40} 24 Td (Page {n} of {len(pages)}) Tj ET")
        stream = "\n".join(ops).encode("cp1252")
        content = add(b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream")
        kids.append(add(
            f"<< /Type /Page /Parent {pages_obj} 0 R /MediaBox [0 0 {width} {height}] "
            f"/Resources << /Font << /F1 {f1} 0 R /F2 {f2} 0 R >> >> /Contents {content} 0 R >>".encode()
        ))
    objects[catalog - 1] = f"<< /Type /Catalog /Pages {pages_obj} 0 R >>".encode()
    objects[pages_obj - 1] = (
        f"<< /Type /Pages /Kids [{' '.join(f'{k} 0 R' for k in kids)}] /Count {len(kids)} >>".encode()
    )
    info = add(f"<< /Title ({esc(title)}) /Producer (pda-shell sample generator) >>".encode())

    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for i, body in enumerate(objects, 1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % i + body + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1)
    for off in offsets:
        out += b"%010d 00000 n \n" % off
    out += b"trailer\n<< /Size %d /Root %d 0 R /Info %d 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (
        len(objects) + 1, catalog, info, xref)
    write(path, bytes(out))


